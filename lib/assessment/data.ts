// The pilot packages as the server holds them: questions, keys and the
// scenario windows' candles (assessment/, generated by its build script).
// Keys and candles never leave through anything but the route, and the play
// part of a window only one candle at a time (non-negotiable #1).

type RawItem = {
  id: string
  type: "scenario" | "mcq_complex" | "mcq_basic"
  order: number
  title?: Text
  pair?: string
  timeframe?: string
  balance?: number
  briefing?: Text
  reason_options?: string[]
  level?: number
  question?: Text
  options?: { id: string; text: Text }[]
}
type RawPackage = {
  package_id: string
  title: Text
  show_risk: boolean
  mechanics: { note: Text }
  reasons: Record<string, Text>
  close_reasons: Record<string, Text>
  items: RawItem[]
}

const RAW = { "P-01": q1, "P-02": q2, "P-03": q3, "P-04": q4, "P-05": q5 } as unknown as Record<PackageId, RawPackage>
const KEYS = { "P-01": k1, "P-02": k2, "P-03": k3, "P-04": k4, "P-05": k5 } as unknown as Record<PackageId, { items: Record<string, ItemKey> }>
const CANDLES = { "P-01": c1, "P-02": c2, "P-03": c3, "P-04": c4, "P-05": c5 } as unknown as Record<PackageId, Record<string, WindowCandles>>

export const pipSizeOf = (pair: string) => (pair.endsWith("JPY") ? 0.01 : 0.0001)

function publicItem(pkg: PackageId, raw: RawItem): PublicItem {
  if (raw.type === "scenario") {
    const key = KEYS[pkg].items[raw.id] as ScenarioKey
    const w = CANDLES[pkg][raw.id]
    const pair = raw.pair as string
    return {
      id: raw.id,
      type: "scenario",
      title: raw.title as Text,
      pair,
      timeframe: raw.timeframe as string,
      balance: raw.balance as number,
      briefing: raw.briefing as Text,
      reasonOptions: raw.reason_options as string[],
      digits: w.digits,
      pipSize: pipSizeOf(pair),
      pipValue: key.numbers.pip_value_usd_per_lot,
      playCandles: w.t.length - w.context,
    }
  }
  return { id: raw.id, type: raw.type, level: raw.level as number, question: raw.question as Text, options: raw.options ?? [] }
}

const cache = new Map<PackageId, PublicPackage>()

/** The package as the browser may see it: questions and facts, no keys. */
export function publicPackage(pkg: PackageId): PublicPackage {
  const hit = cache.get(pkg)
  if (hit) return hit
  const raw = RAW[pkg]
  const out: PublicPackage = {
    id: pkg,
    title: raw.title,
    showRisk: raw.show_risk,
    reasons: raw.reasons,
    closeReasons: raw.close_reasons,
    note: raw.mechanics.note,
    items: [...raw.items].sort((a, b) => a.order - b.order).map((i) => publicItem(pkg, i)),
  }
  cache.set(pkg, out)
  return out
}

export const keyOf = (pkg: PackageId, id: string) => KEYS[pkg].items[id]

const bar = (w: WindowCandles, i: number): Bar => ({ t: w.t[i], o: w.o[i], h: w.h[i], l: w.l[i], c: w.c[i] })

/** The candles shown before Start. */
export function contextBars(pkg: PackageId, id: string): Bar[] {
  const w = CANDLES[pkg][id]
  return Array.from({ length: w.context }, (_, i) => bar(w, i))
}

/** The play part, which is the future until the player has committed. */
export function playBars(pkg: PackageId, id: string): Bar[] {
  const w = CANDLES[pkg][id]
  return Array.from({ length: w.t.length - w.context }, (_, i) => bar(w, w.context + i))
}
